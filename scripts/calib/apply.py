"""Turn Kalibr's camera-IMU result into Sources/WeeeVR/UltraWideCalibration.swift.

usage: python apply.py <calib-camchain-imucam.yaml> <recording meta.json> <out.swift>
Kalibr gives T_cam_imu (IMU -> camera) and timeshift_cam_imu (t_imu = t_cam + shift).
XRSLAM wants camera -> body (= IMU) as q_bc (x y z w) + p_bc, and a time offset added to camera
timestamps, i.e. the same shift.
"""
import json
import sys
from pathlib import Path

import numpy as np
import yaml


def quaternion_xyzw(r: np.ndarray) -> list[float]:
    w = np.sqrt(max(1e-12, 1 + r[0, 0] + r[1, 1] + r[2, 2])) / 2
    x = (r[2, 1] - r[1, 2]) / (4 * w)
    y = (r[0, 2] - r[2, 0]) / (4 * w)
    z = (r[1, 0] - r[0, 1]) / (4 * w)
    q = np.array([x, y, z, w])
    return list(q / np.linalg.norm(q))


def main(result: Path, meta_path: Path, out: Path) -> None:
    cam = yaml.safe_load(result.read_text())["cam0"]
    meta = json.loads(meta_path.read_text())
    fx, fy, cx, cy = cam["intrinsics"]
    k1, k2, p1, p2 = cam["distortion_coeffs"]
    width, height = cam["resolution"]
    t_cam_imu = np.array(cam["T_cam_imu"])
    t_imu_cam = np.linalg.inv(t_cam_imu)
    r_bc, p_bc = t_imu_cam[:3, :3], t_imu_cam[:3, 3]
    q_bc = quaternion_xyzw(r_bc)
    shift = float(cam.get("timeshift_cam_imu", 0.0))
    hfov = np.degrees(2 * np.arctan(width / 2 / fx))
    vfov = np.degrees(2 * np.arctan(height / 2 / fy))

    nominal = np.array([[0, -1, 0], [-1, 0, 0], [0, 0, -1]])   # XRSLAM's iPhone camera -> IMU rotation
    angle = np.degrees(np.arccos(np.clip((np.trace(nominal.T @ r_bc) - 1) / 2, -1, 1)))

    def f(v: float) -> str:
        return repr(float(v))

    out.write_text(f"""// Generated by scripts/calib/apply.py from Kalibr ({result.parent.name}). Do not edit by hand:
// re-run scripts/calib/run.sh to recalibrate.
//
// {meta.get("device")} ultra-wide, {width}x{height} tracking images (1440x1080 GDC, downscaled).
// fov {hfov:.1f}° x {vfov:.1f}°; camera->IMU rotation {angle:.2f}° from XRSLAM's nominal;
// camera {np.linalg.norm(p_bc) * 1000:.1f} mm from the IMU; camera clock + {shift * 1000:.2f} ms = IMU clock.
enum UltraWideCalibration {{
    static let available = true
    static let device = "{meta.get("device")}"
    static let width = {width}, height = {height}
    static let fx = {f(fx)}, fy = {f(fy)}, cx = {f(cx)}, cy = {f(cy)}
    static let distortion = ({f(k1)}, {f(k2)}, {f(p1)}, {f(p2)})   // k1 k2 p1 p2
    static let qBC = ({", ".join(f(v) for v in q_bc)})   // camera -> IMU, x y z w
    static let pBC = ({", ".join(f(v) for v in p_bc)})   // camera in IMU frame, m
    static let timeOffset = {f(shift)}   // s, added to camera timestamps
}}
""")
    print(f"intrinsics fx={fx:.2f} fy={fy:.2f} cx={cx:.2f} cy={cy:.2f} (hfov {hfov:.1f}°), "
          f"distortion {k1:.4f} {k2:.4f} {p1:.5f} {p2:.5f}")
    print(f"camera->IMU: {angle:.2f}° from nominal, p_bc = {np.round(p_bc * 1000, 1)} mm, "
          f"time shift {shift * 1000:.2f} ms")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
